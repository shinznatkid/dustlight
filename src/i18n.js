export const LANGS = ['th', 'en'];
let lang = 'th';
const listeners = [];

export function t(key, vars) {
  let s = STRINGS[lang][key] ?? STRINGS.en[key];
  if (s === undefined) {
    console.warn('i18n: missing', key);
    return key;
  }
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
  return s;
}

export const has = (key) => STRINGS[lang][key] !== undefined || STRINGS.en[key] !== undefined;

// a level's own words ({ th: {...}, en: {...} }), added when its module loads
export function addStrings(table) {
  for (const l of LANGS) Object.assign(STRINGS[l], table[l] ?? {});
}

export function applyDom(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
}

export function setLang(l) {
  lang = LANGS.includes(l) ? l : 'th';
  document.documentElement.lang = lang;
  applyDom();
  for (const fn of listeners) fn(lang);
}

export const getLang = () => lang;
export const onLang = (fn) => listeners.push(fn);
